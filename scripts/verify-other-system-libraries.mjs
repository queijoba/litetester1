import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {SOM6_LIBRARY,TRESDET_LIBRARY,SYSTEM_LIBRARIES} from '../src/components/otherSystemLibraryCatalog.js';
import {applyOtherSystemLibrarySelection} from '../src/components/otherSystemLibraryActions.js';
import {initial3DetPcData,normalize3DetPcData} from '../src/systems/3det/data.js';

const counts=(items)=>items.reduce((a,x)=>(a[x.tipo]=(a[x.tipo]||0)+1,a),{});
assert.deepEqual(counts(SOM6_LIBRARY),{habilidade:24,antecedente:8,tormento:6});
assert.deepEqual(counts(TRESDET_LIBRARY),{vantagem:48,desvantagem:23,arquetipo:24,tecnica:32,pericia:12});
assert.equal(new Set([...SOM6_LIBRARY,...TRESDET_LIBRARY].map(x=>x.id)).size,SOM6_LIBRARY.length+TRESDET_LIBRARY.length);
assert.equal(SYSTEM_LIBRARIES.somdas6.entries.length,38);
assert.equal(SYSTEM_LIBRARIES['3det'].entries.length,139);
for(const entry of [...SOM6_LIBRARY,...TRESDET_LIBRARY])assert.ok(entry.nome&&entry.fonte&&entry.pagina&&entry.desc,'Referência sem fonte: '+entry.id);
assert.ok(SOM6_LIBRARY.some(x=>x.nome==='BORN TO BE WILD'&&x.tipo==='habilidade'));
assert.ok(TRESDET_LIBRARY.some(x=>x.nome==='Ataque Especial'&&x.tipo==='vantagem'));
assert.ok(TRESDET_LIBRARY.some(x=>x.nome==='Absorver Mana'&&x.tipo==='tecnica'&&x.categoria==='Comum'));
assert.ok(TRESDET_LIBRARY.some(x=>x.nome==='Vampiro'&&x.tipo==='arquetipo'));

const som={system:'somdas6',type:'pc',nivel:1,bio:{nome:'Xerife'},antecedentes:{combate:0,labuta:0,negocios:0,montaria:0,tradicao:0,exploracao:0,roubo:0,medicina:0},habilidades:[{nome:'',desc:''},{nome:'',desc:''}],tormento:{tipo:'',desc:'Conteúdo antigo'},anotacoes:'Não apagar'};
const snap=structuredClone(som);
let r=applyOtherSystemLibrarySelection(som,SOM6_LIBRARY.find(x=>x.nome==='PARANOID'),'habilidade');
assert.equal(r.data.habilidades.length,2,'Preencher campo livre sem criar terceiro');
assert.equal(r.data.habilidades[0].nome,'PARANOID');
assert.deepEqual(som,snap,'Não alterar original');
assert.equal(applyOtherSystemLibrarySelection(r.data,SOM6_LIBRARY.find(x=>x.nome==='PARANOID'),'habilidade').changed,false);
r=applyOtherSystemLibrarySelection(r.data,SOM6_LIBRARY.find(x=>x.nome==='Medicina'),'antecedente');
assert.equal(r.data.antecedentes.medicina,1);
assert.equal(r.data.antecedentes.combate,0);
r=applyOtherSystemLibrarySelection(r.data,SOM6_LIBRARY.find(x=>x.nome==='Segredo'),'tormento');
assert.equal(r.data.tormento.tipo,'Segredo');
assert.equal(r.data.tormento.desc,'Conteúdo antigo');
assert.equal(r.data.anotacoes,'Não apagar');
const full={...som,antecedentes:{combate:2,labuta:2,negocios:1,montaria:0,tradicao:0,exploracao:0,roubo:0,medicina:0}};
assert.equal(applyOtherSystemLibrarySelection(full,SOM6_LIBRARY.find(x=>x.nome==='Medicina'),'antecedente').changed,false);

const det=structuredClone(initial3DetPcData);
det.bio.arquetipo='Kemono';
det.vantagens.push({nome:'Vantagem pessoal',custo:'2',desc:'anotações'});
r=applyOtherSystemLibrarySelection(det,TRESDET_LIBRARY.find(x=>x.nome==='Aceleração'),'vantagem');
assert.equal(r.data.vantagens.length,2);
assert.equal(r.data.vantagens[0].desc,'anotações');
assert.equal(r.data.vantagens[1].custo,'1 pt');
assert.equal(applyOtherSystemLibrarySelection(r.data,TRESDET_LIBRARY.find(x=>x.nome==='Aceleração'),'vantagem').changed,false);
r=applyOtherSystemLibrarySelection(r.data,TRESDET_LIBRARY.find(x=>x.nome==='Lento'),'desvantagem');
assert.equal(r.data.desvantagens[0].valor,'–1pt');
r=applyOtherSystemLibrarySelection(r.data,TRESDET_LIBRARY.find(x=>x.nome==='Bola de Fogo'&&x.tipo==='tecnica'),'tecnica');
assert.equal(r.data.tecnicas[0].nome,'Bola de Fogo');
assert.equal(r.data.tecnicas[0].custo,'10 XP');
r=applyOtherSystemLibrarySelection(r.data,TRESDET_LIBRARY.find(x=>x.nome==='Vampiro'),'arquetipo');
assert.equal(r.data.bio.arquetipo,'Vampiro');
assert.equal(r.data.vantagens.length,4,'Pacote Vampiro acrescenta dois benefícios sem remover vantagens manuais');
assert.ok(r.data.vantagens.some(x=>x.origemArquetipo==='Vampiro'&&x.pacoteItem.includes('Talento')),'Benefício por escolha registrado');
assert.ok(r.data.desvantagens.some(x=>x.origemArquetipo==='Vampiro'&&x.pacoteItem==='Fraqueza (Luz do dia)'),'Fraqueza incluída');
assert.equal(r.data.pontos,det.pontos,'Não gastar pontos automaticamente');
assert.equal(normalize3DetPcData(r.data).vantagens[1].pagina,'42–63');
assert.equal(det.bio.arquetipo,'Kemono','Preservar objeto original');
assert.throws(()=>applyOtherSystemLibrarySelection(det,{nome:'Teste',tipo:'magia'},'magia'));
