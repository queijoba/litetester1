import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';

const api=readFileSync('src/cloud/jornadasCloud.js','utf8');
const panel=readFileSync('src/cloud/JornadasPanel.jsx','utf8');
const css=readFileSync('src/cloud/jornadas-night.css','utf8');
const helper=api.slice(api.indexOf('export async function deleteJourney('),api.indexOf('export async function saveJourney('));
assert.ok(helper.includes('const actor=await user()'),'Usuário autenticado antes de excluir');
assert.ok(helper.includes(".from('campaigns')"),'Excluir exclusivamente a campanha');
assert.ok(helper.includes(".eq('id',campaignId).eq('owner_id',actor.id)"),'Exclusão limitada ao dono por id');
assert.ok(helper.includes(".select('id,name')"),'Confirmar exclusão pela resposta do banco');
assert.ok(helper.includes('if(!removed?.length)'),'Exclusão sem registro não pode confirmar sucesso');
assert.ok(!helper.includes(".from('sheets')"),'Não apagar fichas originais');
assert.ok(!helper.includes(".from('groups')"),'Não apagar o grupo');
assert.ok(panel.includes("const [deleteTarget,setDeleteTarget]=React.useState(null)"),'Estado isolado para confirmação');
assert.ok(panel.includes("deleteName!==deleteTarget.name"),'Exigir nome exato');
assert.ok(panel.includes('onClick={confirmDelete}'),'Ação explícita antes da exclusão');
assert.ok(panel.includes('aria-modal="true"')&&panel.includes('role="dialog"'),'Modal acessível');
assert.ok(panel.includes("campaign.owner_id!==account?.id"),'Rejeitar exclusão de campanhas alheias');
assert.ok(panel.includes("g.isOwner&&g.is_dm"),'Mostrar ação somente para mestre responsável');
assert.ok(panel.includes("await deleteJourney(campaignId)"),'Exclusão real pela API');
assert.ok(panel.includes("setJourneys(previous=>previous.filter(c=>c.id!==deleted.id))"),'Remover campanha da lista');
assert.ok(panel.includes("if(active===deleted.id)"),'Sair da sala após apagar');
assert.ok(panel.includes('jornadas-campaign-delete-shortcut'),'Ação na lista de campanhas');
assert.ok(panel.includes('jornadas-campaign-danger-zone'),'Ação nas configurações da campanha');
assert.ok(panel.includes('As fichas originais dos jogadores e suas ameaças NÃO serão apagadas.'),'Confirmar alcance da exclusão');
assert.ok(panel.includes("const allTabs=["),'As abas devem aparecer sem menu extra');
assert.ok(panel.includes("allTabs.map(([key,title])"),'Renderizar todas as abas');
assert.ok(!panel.includes('<select aria-label="Mais recursos da campanha"'),'Remover caixa de recursos');
assert.ok(panel.includes('jornadas-tools-two-rows'),'Navegação em duas linhas');
assert.ok(css.includes('grid-template-columns:repeat(7,minmax(0,1fr))'),'Layout desktop em duas linhas');
assert.ok(css.includes('grid-template-columns:repeat(5,minmax(0,1fr))'),'Layout intermediário responsivo');
assert.ok(css.includes('grid-template-columns:repeat(3,minmax(0,1fr))'),'Layout mobile responsivo');
assert.ok(css.includes('grid-template-columns:repeat(2,minmax(0,1fr))'),'Layout celular estreito');
assert.ok(css.includes('border-bottom:2px solid transparent'),'Abas sem caixas');
assert.ok(css.includes('.jornadas-delete-dialog'),'Modal com tema da Home/Jornadas');
console.log('✓ Campanhas: exclusão confirmada só pelo mestre, fichas preservadas e duas linhas de abas sem dropdown.');
