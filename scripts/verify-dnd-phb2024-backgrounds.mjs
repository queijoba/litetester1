import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {DND_PHB2024_BACKGROUNDS_COUNT,findAbilityPresets} from '../src/components/abilityPresetLibrary.js';
import {getDndLibraryEntries} from '../src/components/dndLibraryFilters.js';
import {buildBackgroundApplication,DND_BACKGROUND_SOURCE} from '../src/components/dndBackgroundActions.js';

globalThis.localStorage={getItem:()=>null,setItem:()=>{},removeItem:()=>{}};
assert.equal(DND_PHB2024_BACKGROUNDS_COUNT,16);
const bgs=findAbilityPresets('dnd5e','antecedentes');
const feats=findAbilityPresets('dnd5e','talentos');
assert.equal(bgs.length,16);
const pages=bgs.map(x=>Number((x.entry.paginaLivro||'').match(/\d+/)?.[0]));
assert.ok(pages.every(n=>n>=178&&n<=185),'Páginas devem usar numeração impressa');
assert.ok(bgs.every(x=>x.entry.pericias.length===2 && x.entry.atributosPermitidos.length===3 && x.entry.ferramenta && x.entry.talentoOriginal));
assert.equal(new Set(bgs.map(x=>x.entry.nome)).size,16);
assert.ok(bgs.every(x=>feats.some(y=>y.entry.nomeOriginal===x.entry.talentoOriginal)),'Todo antecedente precisa ter o talento de origem correspondente');
const acolito=bgs.find(x=>x.entry.nome==='Acólito').entry;
assert.deepEqual(acolito.atributosPermitidos,['int','sab','car']);
assert.equal(acolito.talentoOriginal,'Magic Initiate');
assert.deepEqual(acolito.pericias,['Intuição','Religião']);
const artist=bgs.find(x=>x.entry.nome==='Artista').entry;
assert.equal(artist.talentoOriginal,'Musician');
const soldier=bgs.find(x=>x.entry.nome==='Soldado').entry;
assert.equal(soldier.talentoOriginal,'Savage Attacker');
const human=[{tipo:'classe',nome:'Meu recurso'},{tipo:'talento',nome:'Meu talento customizado'}];
const applied=buildBackgroundApplication(acolito,human,feats);
assert.equal(applied.background,'Acólito');
assert.equal(applied.features.filter(x=>x.bibliotecaOrigem===DND_BACKGROUND_SOURCE).length,2);
assert.ok(applied.features.some(x=>x.nome==='Meu recurso'));
assert.ok(applied.features.some(x=>x.nome==='Meu talento customizado'));
assert.ok(applied.features.some(x=>x.nome==='Iniciado em Magia (Clérigo)'));
assert.deepEqual(applied.skills,['Intuição','Religião']);
assert.equal(applied.moneyAlternative,50);
const switched=buildBackgroundApplication(soldier,applied.features,feats);
assert.equal(switched.features.filter(x=>x.bibliotecaOrigem===DND_BACKGROUND_SOURCE).length,2);
assert.ok(!switched.features.some(x=>x.nome==='Iniciado em Magia (Clérigo)'));
assert.ok(switched.features.some(x=>x.nome==='Atacante Selvagem'));
assert.ok(switched.features.some(x=>x.nome==='Meu talento customizado'));
const reapplied=buildBackgroundApplication(soldier,switched.features,feats);
assert.equal(reapplied.features.filter(x=>x.bibliotecaOrigem===DND_BACKGROUND_SOURCE).length,2);
const previousFeat=feats.find(x=>x.entry.nomeOriginal==='Lucky').entry;
const withManual=buildBackgroundApplication(bgs.find(x=>x.entry.nome==='Andarilho').entry,
[{tipo:'talento',nome:previousFeat.nome,featId:previousFeat.id}],feats);
assert.equal(withManual.featAlreadyPresent,true);
assert.equal(withManual.features.filter(x=>x.tipo==='talento').length,1);
assert.ok(getDndLibraryEntries({tab:'antecedentes',query:'Medicina'}).some(x=>x.entry.nome==='Eremita'));
assert.ok(getDndLibraryEntries({tab:'antecedentes',query:'Cartógrafo'}).some(x=>x.entry.nome==='Guia'));
assert.ok(getDndLibraryEntries({tab:'antecedentes',query:'Músico'}).some(x=>x.entry.nome==='Artista'));
const app=readFileSync('src/PJLiteApp.jsx','utf8');
const modal=readFileSync('src/components/DndLibraryModal.jsx','utf8');
assert.ok(app.includes("if(tab==='antecedentes')"));
assert.ok(app.includes("updateField('bio.antecedente'"));
assert.ok(modal.includes("['antecedentes','Antecedentes']"));
assert.ok(!app.includes("setMobileTab('habilidades')"),'Somente abas existentes devem ser usadas');
console.log('✓ D&D Livro do Jogador: 16 antecedentes com talentos, perícias, páginas e aplicação preservando a ficha.');
